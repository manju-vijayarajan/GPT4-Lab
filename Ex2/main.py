import gradio as gr
import requests
OLLAMA_URL = "http://localhost:11434/api/generate"
MODEL_NAME = "qwen2.5:0.5b"
def generate_blog(outline_text):
    if not outline_text.strip():
        return "Please enter a blog outline."
    outline = [
        line.strip()
        for line in outline_text.split("\n")
        if line.strip()
    ]
    prompt = """
Write a detailed blog post based on the following outline.
Requirements:
- Use Markdown formatting.
- Include a suitable title.
- Explain each point clearly.
- Make the content informative and engaging.
- End with a conclusion.
- Do not mention that the content was generated by AI.
Outline:
"""
    prompt += "\n".join(
        f"{i + 1}. {line}"
        for i, line in enumerate(outline)
    )
    try:
        response = requests.post(
            OLLAMA_URL,
            json={
                "model": MODEL_NAME,
                "prompt": prompt,
                "stream": False
            },
            timeout=120
        )
        response.raise_for_status()
        data = response.json()
        return data["response"]
    except requests.exceptions.ConnectionError:
        return (
            "Error: Could not connect to Ollama. "
            "Make sure Ollama is running."
        )
    except requests.exceptions.Timeout:
        return "Error: The model took too long to respond."
    except Exception as e:
        return f"Error: {str(e)}"
def main():
    interface = gr.Interface(
        fn=generate_blog,
        inputs=gr.Textbox(
            lines=10,
            placeholder=(
                "Enter your blog outline, one topic per line...\n\n"
                "Introduction\n"
                "Role of AI in Education\n"
                "Applications of AI\n"
                "Benefits and Challenges\n"
                "Future Trends\n"
                "Conclusion"
            ),
            label="Blog Outline"
        ),
        outputs=gr.Markdown(
            label="Generated Blog Content"
        ),
        title="AI-Powered Blog Content Generator",
        description=(
            "Enter a blog outline and generate a "
            "well-structured blog using a local AI model."
        )
    )
    interface.launch()
if __name__ == "__main__":
    main()